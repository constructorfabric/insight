"""Semgrep's hash lock is the compile output of its source pin."""

from __future__ import annotations

import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
GITHUB = ROOT / ".github"
DEPENDABOT = GITHUB / "dependabot.yml"
SOURCE = GITHUB / "semgrep-requirements.in"
LOCK = GITHUB / "semgrep-requirements.txt"
SECURITY = GITHUB / "workflows" / "security.yml"

_PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(\[[^\]]+\])?==(\S+)")


def hashed_pins(text: str) -> list[tuple[str, str]]:
    pins: list[tuple[str, str]] = []
    lines = text.splitlines()
    index = 0
    while index < len(lines):
        match = _PIN.match(lines[index])
        if match is None:
            index += 1
            continue
        name, version = match.group(1), match.group(3)
        block = [lines[index]]
        index += 1
        while index < len(lines) and lines[index].startswith("    "):
            block.append(lines[index])
            index += 1
        if not any(line.strip().startswith("--hash=sha256:") for line in block):
            raise AssertionError(f"{name}=={version} has no sha256 digest")
        pins.append((name, version.rstrip("\\")))
    return pins


class SemgrepLockTests(unittest.TestCase):
    def test_the_hashed_lock_is_the_compile_of_the_source_pin(self) -> None:
        source = SOURCE.read_text(encoding="utf-8").strip()
        self.assertRegex(source, r"^semgrep==\d+\.\d+\.\d+$")
        lock = LOCK.read_text(encoding="utf-8")
        header = "\n".join(lock.splitlines()[:6])
        self.assertIn("autogenerated by pip-compile", header)
        self.assertIn(".github/semgrep-requirements.in", header)
        self.assertNotIn("--no-index", header)

        pins = dict(hashed_pins(lock))
        self.assertEqual(pins["semgrep"], source.split("==", 1)[1])
        self.assertGreater(len(pins), 1)
        self.assertEqual(
            sorted(path.name for path in GITHUB.rglob("*.in")),
            ["semgrep-requirements.in"],
        )

    def test_dependabot_recompiles_that_directory(self) -> None:
        text = DEPENDABOT.read_text(encoding="utf-8")
        start = text.index("  - package-ecosystem: pip\n    directory: /.github\n")
        block = text[start : start + 500]
        self.assertIn("interval: weekly", block)
        self.assertIn("default-days: 7", block)
        self.assertIn("versioning-strategy: increase", block)
        self.assertIn("trufflehog-allowlist.txt", block)
        self.assertIn('patterns: ["*"]', block)

    def test_the_semgrep_lane_installs_that_lock_on_python_3_12(self) -> None:
        security = SECURITY.read_text(encoding="utf-8")
        self.assertEqual(security.count("--require-hashes -r .github/semgrep-requirements.txt"), 2)
        self.assertIn('uv venv --python 3.12 "$RUNNER_TEMP/semgrep"', security)
        self.assertEqual((GITHUB / ".python-version").read_text(encoding="utf-8").strip(), "3.12")


if __name__ == "__main__":
    unittest.main()
